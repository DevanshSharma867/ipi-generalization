"""
agent_pipeline.py
=================
Agent-style synthetic tool outputs (paper_plan A3, §7 step 3). Templates: src/agent_tools.py (19 tool types, no
AgentDojo/tau-bench template or domain). Programmatic only: templates plus randomised fields, no LLM, no GPU.

Two products, both in the agent-set input format (`Intent: <user request> | Context: <one tool output>`):

1. data/agent_v1/calibration_pool.csv (unchanged since F019; regenerated and verified, never rewritten): CAL_PER_TOOL clean, raw tool outputs per tool (no inserted span), generated from its own
   RNG stream, independent of every split seed. It is held out from all training: every training realization
   rejects any output text that is in the pool, and the pool is never used as a clean-B donor. Its size and sha256
   are in calibration_manifest.json (A3: recorded before any model is scored on an agent set).
2. data/agent_v2/split_seed_<k>/{train,val}.csv: training data in V3's row design (docs/v3_design.md), V3 columns. Per output
   ("doc"): 2 injected + clean_a + clean_b, each with exactly ONE span inserted by V3's insertion code
   (probes.insert_preserving with V3_BOUNDARIES; position and separator i.i.d. per row, independent of the label).
     injected  BIPIA TRAIN attack file only (text register): `train` uses V3's train categories, `val` V3's held-out
               val categories (D7); BIPIA test attacks are never loaded
     clean_a   a benign, human-addressed instruction from agent_tools templates (tool-specific + generic), filled
               with the output's own fields; template ids are partitioned train/val (every 4th to val); each template
               also has length variants (CLEAN_A_SUFFIXES), and match_span picks the joint length/form match to a drawn attack of the split
     clean_b   a neutral prose sentence spliced from another output of the same split (any tool: several tools have
               no free text), each sentence used at most DONOR_K times, chosen with match_span (joint length/form
               match to a random attack of the same split; all attacks come from the BIPIA train file)
   `val` is the held-out split for the V3 shortcut gates (scripts/artifact_baselines.py --eval_split val).
   Training sets are regenerated byte-identically from the seed and are not committed; their sha256 is in the
   manifest.

    python src/agent_pipeline.py --split_seeds 0 1 2 3 4 [--output_dir data/agent_v2]
"""

import argparse
import hashlib
import json
import math
import random
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Dict, List

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from agent_tools import GENERATORS, INTENTS, TOOLS, clean_a_templates, fill
from data_pipeline_v3 import (COLUMNS, MARGIN, MAX_TOKENS, POSITIONS, SEPARATORS, TOKENIZER, check,
                              load_attack_pools, make_row, normalize_span, sha256_file, span_cost)
from probes import form_tags
from preprocess import build_combined_text
from runlog import assert_not_frozen

VERSION = "agent_v2"      # training data; v1 (F019) had a span length/form shortcut inside train (agent_form_cv.py)
CAL_VERSION = "agent_v1"  # the calibration pool is unchanged since F019: same RNG stream, verified byte-identical
CAL_DIR = ROOT / "data" / CAL_VERSION
N_DOCS = {"train": 120, "val": 60}          # per tool; val sized for per-tool gate estimates
CAL_PER_TOOL = 60                           # 19 tools -> 1,140 >= 1,000 (A3)
DONOR_K = 2
CLEAN_B_WORDS = (4, 16)
# Length variants of every clean-A template (a clause before the final punctuation), so matching can reach the
# attack length range of each split
CLEAN_A_SUFFIXES = ("", " today", " when convenient", " if that works for you", " before the end of the week",
                    " whenever you have a spare moment this afternoon")
MATCH_BINARY = ("ends_q", "ends_dot", "has_quote", "has_digit", "has_newline_or_code_char", "has_you")


def with_suffix(text: str, suffix: str) -> str:
    return text if not suffix or text[-1] not in ".?!" else text[:-1] + suffix + text[-1]


def split_profile(attacks: List[dict]) -> List[dict]:
    """Form tags of one split's attack strings (all from the BIPIA train file): the matching targets."""
    return [form_tags(normalize_span(a["text"])) for a in attacks]


USAGE_COST = 0.02
MAX_TRIES = 200


def match_span(cands: List[dict], r: random.Random, targets: List[dict], usage) -> dict:
    """Joint form match to one attack string drawn from the split: log-distance in words and chars, plus
    2 x |cap_ratio difference|, plus 0.5 per mismatched binary feature, plus USAGE_COST x usage (spreads
    templates); ties broken by the RNG."""
    t0 = r.choice(targets)
    cands = list(cands)
    r.shuffle(cands)
    def cost(c):
        t = c["tags"]
        return (abs(math.log(max(t["n_words"], 1) / t0["n_words"])) + abs(math.log(max(t["n_chars"], 1) / t0["n_chars"]))
                + 2 * abs(t["cap_ratio"] - t0["cap_ratio"]) + 0.5 * sum(t[f] != t0[f] for f in MATCH_BINARY)
                + USAGE_COST * usage(c))
    return min(cands, key=cost)


def rng_for(stage: str) -> random.Random:
    return random.Random(f"{VERSION}:{stage}")


def load_tokenizer():
    from transformers import AutoTokenizer
    from transformers.utils import logging as hf_logging
    hf_logging.set_verbosity_error()
    return AutoTokenizer.from_pretrained(str(TOKENIZER))


def n_tokens(tok, intent: str, text: str) -> int:
    return len(tok(build_combined_text({"user_intent": intent, "text": text}))["input_ids"])


def make_outputs(tool: str, n: int, r: random.Random, prefix: str, tok, cap: int, taken: set) -> List[dict]:
    """n distinct outputs of one tool whose `Intent | Context` leaves room for the largest span (cap tokens)."""
    out = []
    for i in range(n):
        for _ in range(MAX_TRIES):
            o = GENERATORS[tool](r)
            intent = fill(r.choice(INTENTS[tool]), o.fields)
            if o.text not in taken and n_tokens(tok, intent, o.text) + cap <= MAX_TOKENS - MARGIN:
                break
        else:
            raise RuntimeError(f"{tool}: no distinct output that fits after {MAX_TRIES} tries")
        taken.add(o.text)
        did = f"{prefix}_{tool}_{i:04d}"
        out.append({"doc_id": did, "task_type": tool, "user_intent": intent, "context": o.text, "main_context": o.text,
                    "fields": o.fields, "prose": [normalize_span(p) for p in o.prose], "trimmed": False,
                    "component": did})
    return out


def calibration_pool(tok, cap: int) -> pd.DataFrame:
    r, taken, rows = random.Random(f"{CAL_VERSION}:calibration"), set(), []
    for tool in TOOLS:
        for d in make_outputs(tool, CAL_PER_TOOL, r, "cal", tok, cap, taken):
            rows.append(make_row(d, d["context"], None, "none", "", {
                "id": f"{d['doc_id']}_raw", "split_seed": "", "split": "calibration", "eval_slice": "calibration",
                "label": 0, "row_type": "raw_clean", "span_source": "", "attack_category": "", "attack_source": "",
                "clean_type": "raw"}))
    df = pd.DataFrame(rows)
    df["n_tokens"] = [n_tokens(tok, i, t) for i, t in zip(df["user_intent"], df["text"])]
    return df[COLUMNS]


def pick(r: random.Random, items: list, counts: Counter, key, n=1):
    """n distinct least-used items (ties broken by the stage RNG); same rule as data_pipeline_v3.pick."""
    cand = list(items)
    r.shuffle(cand)
    cand.sort(key=lambda x: counts[key(x)])
    if len(cand) < n:
        raise RuntimeError("pool exhausted")
    for x in cand[:n]:
        counts[key(x)] += 1
    return cand[:n]


def build(split_seed: int, tok, cal_texts: set, cap: int) -> dict:
    atk = load_attack_pools()["text"]
    s = lambda stage: rng_for(f"{split_seed}:{stage}")
    r_gen, r_pos, r_atk, r_ben, r_don = (s(x) for x in ("outputs", "positions", "attacks", "clean_a", "clean_b"))
    taken = set(cal_texts)
    docs = {(t, sp): make_outputs(t, n, r_gen, f"s{split_seed}{sp[0]}", tok, cap, taken)
            for sp, n in N_DOCS.items() for t in TOOLS}

    # clean-B donor sentences per split, from every tool's outputs (several tools have no free text); a sentence
    # that occurs in both splits is dropped from both
    donors = {sp: [{"text": p, "donor": d["doc_id"], "tags": form_tags(p)} for (_, s2), ds in docs.items() if s2 == sp for d in ds
                   for p in d["prose"] if CLEAN_B_WORDS[0] <= len(p.split()) <= CLEAN_B_WORDS[1]] for sp in N_DOCS}
    both = {c["text"] for c in donors["train"]} & {c["text"] for c in donors["val"]}
    donors = {sp: [c for c in cs if c["text"] not in both] for sp, cs in donors.items()}

    profiles = {sp: split_profile(atk[sp]) for sp in N_DOCS}  # each split matched to its own attacks (train file)
    templates = clean_a_templates()
    split_of_template = lambda tid: "val" if int(tid.rsplit(":", 1)[1]) % 4 == 3 else "train"
    place = lambda: (r_pos.choice(POSITIONS), r_pos.choice(SEPARATORS))
    atk_n, ben_n, don_n = Counter(), Counter(), Counter()
    rows = []
    for (tool, split), ds in docs.items():
        tpl = [x for x in templates if x[1] in (tool, None) and split_of_template(x[0]) == split]
        for d in ds:
            ctx, base = d["context"], {"split_seed": split_seed, "split": split, "eval_slice": "main"}
            for k, a in enumerate(pick(r_atk, atk[split], atk_n, lambda x: x["text"], n=2)):
                rows.append(make_row(d, ctx, a["text"], *place(), {
                    **base, "id": f"{d['doc_id']}_inj{k}", "label": 1, "row_type": "injected",
                    "span_source": a["category"], "attack_category": a["category"], "attack_source": a["source"],
                    "clean_type": ""}))
            # every template x length variant of this tool, matched to the split's attacks; usage breaks ties
            cands = [{"tid": x[0], "text": with_suffix(fill(x[2], d["fields"]), sfx)} for x in tpl
                     for sfx in CLEAN_A_SUFFIXES]
            for c in cands:
                c["tags"] = form_tags(normalize_span(c["text"]))
            ca = match_span(cands, r_ben, profiles[split], lambda x: ben_n[(tool, x["tid"])])
            ben_n[(tool, ca["tid"])] += 1
            tid = ca["tid"]
            rows.append(make_row(d, ctx, ca["text"], *place(), {
                **base, "id": f"{d['doc_id']}_cleanA", "label": 0, "row_type": "clean_a", "span_source": tid,
                "attack_category": "", "attack_source": "", "clean_type": "benign_imperative"}))
            pool = [c for c in donors[split] if c["donor"] != d["doc_id"] and c["text"] not in ctx
                    and don_n[c["text"]] < DONOR_K]
            if not pool:
                raise RuntimeError(f"no clean-B donor left for {d['doc_id']}")
            c = match_span(pool, r_don, profiles[split], lambda x: don_n[x["text"]])
            don_n[c["text"]] += 1
            rows.append(make_row(d, ctx, c["text"], *place(), {
                **base, "id": f"{d['doc_id']}_cleanB", "label": 0, "row_type": "clean_b",
                "span_source": f"donor:{c['donor']}", "attack_category": "", "attack_source": "",
                "clean_type": "spliced_neutral"}))
    main = pd.DataFrame(rows)
    main["n_tokens"] = [n_tokens(tok, i, t) for i, t in zip(main["user_intent"], main["text"])]
    main = main[COLUMNS]
    flat = pd.DataFrame([{**d, "split": sp} for (_, sp), ds in docs.items() for d in ds])
    check(main, flat)
    assert not set(main["text"]) & cal_texts, "a training row equals a calibration output"
    assert not set(flat["context"]) & cal_texts, "a training output is in the calibration pool"
    return {"main": main}


def write_csv(df: pd.DataFrame, p: Path) -> str:
    df.to_csv(p, index=False, lineterminator="\n")
    return sha256_file(p)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--split_seeds", type=int, nargs="+", default=[0, 1, 2, 3, 4])
    ap.add_argument("--output_dir", type=Path, default=ROOT / "data" / VERSION)
    a = ap.parse_args()
    assert_not_frozen(a.output_dir)
    a.output_dir.mkdir(parents=True, exist_ok=True)
    tok = load_tokenizer()
    atk = load_attack_pools()["text"]
    cap = max(span_cost(tok, x["text"]) for x in atk["train"] + atk["val"])
    # clean-A/B spans are shorter than the longest attack; check() re-verifies every row is <= MAX_TOKENS
    common = {"version": VERSION, "generator": "src/agent_pipeline.py + src/agent_tools.py", "tools": list(TOOLS),
              "n_tools": len(TOOLS), "span_cap_tokens": cap, "max_tokens": MAX_TOKENS, "margin": MARGIN,
              "tokenizer": str(TOKENIZER.relative_to(ROOT))}

    cal = calibration_pool(tok, cap)
    cal_path = CAL_DIR / "calibration_pool.csv"
    cal_bytes = cal.to_csv(index=False, lineterminator="\n").encode()
    cal_sha = hashlib.sha256(cal_bytes).hexdigest()
    if cal_path.exists():  # recorded pool (A3): never rewritten, only verified
        recorded = json.loads((CAL_DIR / "calibration_manifest.json").read_text())["sha256"]
        assert cal_sha == recorded == sha256_file(cal_path), "calibration pool would change; it is recorded (F019)"
    else:
        CAL_DIR.mkdir(parents=True, exist_ok=True)
        cal_path.write_bytes(cal_bytes)
    cal_manifest = {**common, "version": CAL_VERSION, "file": cal_path.name, "rows": len(cal),
                    "per_tool": CAL_PER_TOOL, "distinct_texts": int(cal["text"].nunique()), "sha256": cal_sha,
                    "label": "all clean (0), raw tool outputs, no inserted span",
                    "rng_stream": f"{CAL_VERSION}:calibration (independent of split seeds)"}
    assert cal_manifest["distinct_texts"] == len(cal) >= 1000
    if not (CAL_DIR / "calibration_manifest.json").exists():
        (CAL_DIR / "calibration_manifest.json").write_text(json.dumps(cal_manifest, indent=2, sort_keys=True) + "\n")
    print(f"calibration pool: {len(cal)} rows, sha256 {cal_manifest['sha256']}")

    cal_texts = set(cal["text"])
    inputs = {f: sha256_file(ROOT / "data" / "raw" / "BIPIA" / "benchmark" / f) for f in ("text_attack_train.json",)}
    for k in a.split_seeds:
        res = build(k, tok, cal_texts, cap)
        out = a.output_dir / f"split_seed_{k}"
        out.mkdir(exist_ok=True)
        m = res["main"]
        files = {f"{sp}.csv": write_csv(m[m["split"] == sp], out / f"{sp}.csv") for sp in N_DOCS}
        manifest = {**common, "split_seed": k, "files_sha256": files, "inputs_sha256": inputs,
                    "calibration_pool_sha256": cal_manifest["sha256"], "docs_per_tool": N_DOCS, "donor_k": DONOR_K,
                    "counts": {sp: {rt: int(n) for rt, n in g["row_type"].value_counts().sort_index().items()}
                               for sp, g in m.groupby("split")},
                    "attack_categories": {sp: sorted(g.loc[g["label"] == 1, "attack_category"].unique())
                                          for sp, g in m.groupby("split")},
                    "max_n_tokens": int(m["n_tokens"].max())}
        (out / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
        print(f"split_seed {k}: {manifest['counts']} max_tokens {manifest['max_n_tokens']}")


if __name__ == "__main__":
    main()
