"""
make_findings.py
================
Render docs/findings.md from docs/findings.src.md, filling every number from paper/numbers.tex.

In the source, {{Name}} becomes "`\\Name` = <value>" and {{Name|ci}} becomes "`\\Name` = <value> [<lo>, <hi>]"
with the CI taken from \\NameCiLo / \\NameCiHi. A missing macro is an error, so no number can be typed by hand.

    python scripts/make_findings.py      # run after scripts/make_tables.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "docs" / "findings.src.md", ROOT / "docs" / "findings.md"


def main():
    macros = dict(re.findall(r"\\newcommand\{\\(\w+)\}\{([^}]*)\}", (ROOT / "paper" / "numbers.tex").read_text()))
    missing = []

    def fill(m):
        name, with_ci = m.group(1), m.group(2) == "|ci"
        keys = [name] + ([name + "CiLo", name + "CiHi"] if with_ci else [])
        missing.extend(k for k in keys if k not in macros)
        if any(k not in macros for k in keys):
            return m.group(0)
        s = f"`\\{name}` = {macros[name]}"
        return s + f" [{macros[name + 'CiLo']}, {macros[name + 'CiHi']}]" if with_ci else s

    body = re.sub(r"\{\{(\w+)(\|ci)?\}\}", fill, SRC.read_text())
    if missing:
        sys.exit("missing macros in paper/numbers.tex: " + ", ".join(sorted(set(missing))))
    OUT.write_text("<!-- Generated by scripts/make_findings.py from docs/findings.src.md and paper/numbers.tex; "
                   "edit the .src.md -->\n" + body)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
